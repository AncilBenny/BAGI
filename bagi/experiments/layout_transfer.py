"""Gate A6: frozen learned-world-model transfer to a mirrored Workshop layout.

No training or oracle inputs go to the learned model. The mirrored layout is
generated by an exact geometry symmetry, retaining the same causal rules.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import torch
import yaml

from bagi.experiments.dataset_foundations import model_input
from bagi.experiments.reachable_state_holdout import (
    enumerate_reachable,
    make_groups,
    score_transitions,
    split_training_keys,
)
from bagi.models import WorldModel
from bagi.worlds import WorkshopEnv


def run(config_path: str) -> dict:
    cfg = yaml.safe_load(Path(config_path).read_text(encoding="utf-8"))
    env_cfg = cfg["environment"]
    data_cfg = cfg["training_data"]
    model_cfg = cfg["model"]
    data_file = Path(data_cfg["transitions"])
    checkpoint = Path(model_cfg["checkpoint"])
    if not data_file.is_file() or not checkpoint.is_file():
        raise FileNotFoundError("Requires original cached training data and model checkpoint")
    records = [
        json.loads(line) for line in data_file.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    training_keys = split_training_keys(
        records, int(data_cfg["training_seed"]),
        float(data_cfg["validation_fraction"]),
    )
    original_env = WorkshopEnv(**env_cfg, layout_mode="default")
    model = WorldModel(
        observation_shape=tuple(original_env.observation_space.shape),
        actions=int(model_cfg["actions"]),
        cell_values=int(model_cfg["cell_values"]),
        hidden=int(model_cfg["hidden"]),
    )
    model.load_state_dict(torch.load(checkpoint, map_location="cpu", weights_only=True))
    model.eval()
    results = {}
    input_keys = {}
    for mode in ("default", "mirror_x"):
        env = WorkshopEnv(**env_cfg, layout_mode=mode)
        transitions, graph = enumerate_reachable(env)
        visible_keys = {model_input(row) for row in transitions}
        groups = make_groups(transitions, training_keys)
        input_keys[mode] = visible_keys
        results[mode] = {
            "graph": graph,
            "unique_visible_state_action_keys": len(visible_keys),
            "seen_in_original_training": score_transitions(
                model, groups.get("seen_in_training", [])
            ),
            "unseen_in_original_training": score_transitions(
                model, groups.get("unseen_observation_action", [])
            ),
            "all_state_action_transitions": score_transitions(model, transitions),
        }
        print(f"{mode}: {graph['state_action_transitions']} simulator transitions "
              f"cell_accuracy={results[mode]['all_state_action_transitions']['cell_accuracy']:.4f} "
              f"whole_accuracy={results[mode]['all_state_action_transitions']['whole_observation_accuracy']:.4f}")
    original = results["default"]["all_state_action_transitions"]
    mirrored = results["mirror_x"]["all_state_action_transitions"]
    output = {
        "question": "Does the original frozen local-view world model predict one-step transitions of the exact horizontally mirrored Workshop rules?",
        "model_training_layout": "default_only",
        "checkpoint": str(checkpoint),
        "original_training_data": str(data_file),
        "original_training_unique_keys": len(training_keys),
        "results": results,
        "mirror_visible_keys_absent_from_original_reachable_graph": len(
            input_keys["mirror_x"] - input_keys["default"]
        ),
        "mirror_visible_keys_absent_from_original_training": len(
            input_keys["mirror_x"] - training_keys
        ),
        "mirror_minus_original_cell_accuracy": (
            mirrored["cell_accuracy"] - original["cell_accuracy"]
        ),
        "mirror_minus_original_whole_accuracy": (
            mirrored["whole_observation_accuracy"] -
            original["whole_observation_accuracy"]
        ),
        "limits": [
            "Mirror is an exact reflection of the same causal rules, not a novel rule family.",
            "The model is evaluated zero-shot without training on mirrored transitions.",
            "The original and mirrored reachable-state graphs are exhaustive for their respective deterministic worlds, not IID held-out samples.",
            "Full hidden state is used only to enumerate reachable states; the model sees local observation and action only.",
            "The original training set was known to have severe exact transition overlap with its own validation split.",
            "Cell/whole prediction accuracy, not goal-reaching or transfer learning speed, is measured.",
        ],
    }
    path = Path(cfg["evaluation"]["output_dir"]) / "summary.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(output, indent=2), encoding="utf-8")
    print(f"Mirror keys absent from original reachable graph: "
          f"{output['mirror_visible_keys_absent_from_original_reachable_graph']}")
    print(f"Saved symmetry transfer: {path}")
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/layout_transfer.yaml")
    run(parser.parse_args().config)
