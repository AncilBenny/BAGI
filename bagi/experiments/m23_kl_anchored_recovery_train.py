"""Stage26 prospectively mixed 64:64 real source replay and executed recovery labels.

No synthetic/native actions are generated by this optimizer; prior source-frozen
weights and both arms' actual environment acquisition are shared and unchanged.
"""
from __future__ import annotations

import copy
import hashlib
import time

import numpy as np
import torch
from torch import nn

from bagi.experiments.m23_executed_recovery_train import (
    EPISODES_PER_STEP,
    FOLLOWUP_UPDATES,
    TOKENS_PER_UPDATE,
    model_sha256,
    prepare_label_pool,
)
from bagi.experiments.m23_source_interaction_context_bc import (
    LR,
    MODEL_SEEDS,
    InteractionContextGRU,
)

FIT_ARMS = ("mixed_unanchored", "mixed_kl_anchored")
ANCHOR_KL_COEFFICIENT = 1.0
SOURCE_LABELS_PER_STEP = 64
RECOVERY_LABELS_PER_STEP = 64


def fit_stage26_followup(
    teacher: list[dict], acquired: list[dict],
    frozen: InteractionContextGRU, seed: int, arm: str,
    class_weights: torch.Tensor,
) -> tuple[InteractionContextGRU, dict]:
    """Same 64:64 actually executed source labels with optional frozen-policy KL."""
    if arm not in FIT_ARMS or seed not in MODEL_SEEDS:
        raise ValueError("Stage26 unregistered source/recovery model arm or seed")
    if (frozen.training or class_weights.shape != (7,)
            or not torch.isfinite(class_weights).all()
            or SOURCE_LABELS_PER_STEP + RECOVERY_LABELS_PER_STEP
            != TOKENS_PER_UPDATE or EPISODES_PER_STEP != 16):
        raise ValueError("Stage26 frozen public source/mixed label-budget violation")
    source_pool, source_meta = prepare_label_pool(
        teacher, acquired, seed, "source_replay"
    )
    recovery_pool, recovery_meta = prepare_label_pool(
        teacher, acquired, seed, "executed_rescue"
    )
    if not source_pool or not recovery_pool:
        raise ValueError("Stage26 matched source and genuinely executed suffix absent")
    before = model_sha256(frozen)
    model = copy.deepcopy(frozen)
    if model_sha256(model) != before:
        raise ValueError("Stage26 frozen source initialization differs")
    model.train()
    optimizer = torch.optim.Adam(model.parameters(), lr=LR)
    rng = np.random.default_rng(26_300_000 + seed)
    actual_updates = label_presentations = replay_presented = recovery_presented = 0
    loss_sum = 0.0
    kl_sum = 0.0
    label_selection_sha = hashlib.sha256()
    started = time.perf_counter()
    for _ in range(FOLLOWUP_UPDATES):
        source_rows = [
            source_pool[int(i)]
            for i in rng.integers(0, len(source_pool), size=EPISODES_PER_STEP // 2)
        ]
        recovery_rows = [
            recovery_pool[int(i)]
            for i in rng.integers(0, len(recovery_pool), size=EPISODES_PER_STEP // 2)
        ]
        chosen = source_rows + recovery_rows
        x = nn.utils.rnn.pad_sequence(
            [torch.from_numpy(row["x"]).clone() for row, _ in chosen],
            batch_first=True,
        )
        labels = nn.utils.rnn.pad_sequence(
            [torch.from_numpy(row["y"]) for row, _ in chosen],
            batch_first=True, padding_value=-100,
        )
        masks = nn.utils.rnn.pad_sequence(
            [torch.from_numpy(mask) for _, mask in chosen],
            batch_first=True, padding_value=False,
        )
        if torch.any(masks & (labels == -100)):
            raise ValueError("Stage26 padded or imagined label was supervised")
        first_half = torch.nonzero(masks[:EPISODES_PER_STEP // 2], as_tuple=False)
        second_half = torch.nonzero(masks[EPISODES_PER_STEP // 2:], as_tuple=False)
        if not len(first_half) or not len(second_half):
            raise ValueError("Stage26 mixed real label strata have no valid actions")
        source_selection = first_half[torch.from_numpy(
            rng.integers(0, len(first_half), size=SOURCE_LABELS_PER_STEP)
            .astype(np.int64)
        )]
        suffix_selection = second_half[torch.from_numpy(
            rng.integers(0, len(second_half), size=RECOVERY_LABELS_PER_STEP)
            .astype(np.int64)
        )].clone()
        suffix_selection[:, 0] += EPISODES_PER_STEP // 2
        selected = torch.cat((source_selection, suffix_selection))
        if len(selected) != TOKENS_PER_UPDATE:
            raise ValueError("Stage26 64+64 actual supervised label count wrong")
        optimizer.zero_grad()
        logits = model(x)
        targets = labels[selected[:, 0], selected[:, 1]]
        if torch.any((targets < 0) | (targets > 6)):
            raise ValueError("Stage26 mixed source loss uses illegal native action")
        supervised_loss = nn.functional.cross_entropy(
            logits[selected[:, 0], selected[:, 1]], targets,
            weight=class_weights,
        )
        source_kl = torch.zeros((), dtype=supervised_loss.dtype)
        if arm == "mixed_kl_anchored":
            # Only real TRAIN source positions, with frozen public-only
            # logits detached. No target, monitor, auditor, or reward signals.
            with torch.no_grad():
                original_logits = frozen(x)
                frozen_source_probs = torch.softmax(
                    original_logits[source_selection[:, 0], source_selection[:, 1]],
                    dim=-1,
                )
            live_source_log_probs = torch.log_softmax(
                logits[source_selection[:, 0], source_selection[:, 1]],
                dim=-1,
            )
            source_kl = nn.functional.kl_div(
                live_source_log_probs, frozen_source_probs,
                reduction="batchmean",
            )
        loss = supervised_loss + ANCHOR_KL_COEFFICIENT * source_kl
        if not (torch.isfinite(loss) and torch.isfinite(supervised_loss)
                and torch.isfinite(source_kl)):
            raise ValueError("Stage26 source public KL or native loss nonfinite")
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        actual_updates += 1
        label_presentations += len(selected)
        replay_presented += len(source_selection)
        recovery_presented += len(suffix_selection)
        label_selection_sha.update(
            selected.detach().cpu().numpy().astype(np.int64).tobytes()
        )
        loss_sum += float(supervised_loss.detach())
        kl_sum += float(source_kl.detach())
    if (actual_updates != FOLLOWUP_UPDATES
            or replay_presented != FOLLOWUP_UPDATES * SOURCE_LABELS_PER_STEP
            or recovery_presented != FOLLOWUP_UPDATES * RECOVERY_LABELS_PER_STEP
            or label_presentations != FOLLOWUP_UPDATES * TOKENS_PER_UPDATE
            or model_sha256(frozen) != before):
        raise ValueError("Stage26 optimizer/real mixed label count or frozen hash changed")
    model.eval()
    return model, {
        "arm": arm,
        "model_seed": seed,
        "frozen_base_model_sha256": before,
        "source_expert_only_initialization": True,
        "supervision_distribution": "64_original_source_replay_plus_64_executed_rescue",
        "frozen_source_kl_weight": (
            ANCHOR_KL_COEFFICIENT if arm == "mixed_kl_anchored" else 0.0
        ),
        "frozen_policy_anchor_train_source_only": True,
        "paired_actual_label_selection_sha256": label_selection_sha.hexdigest(),
        "model_parameters": sum(p.numel() for p in model.parameters()),
        "real_optimizer_updates": actual_updates,
        "episodes_per_real_update": EPISODES_PER_STEP,
        "fixed_supervised_native_labels_per_update": TOKENS_PER_UPDATE,
        "actual_cached_label_presentations_not_native_steps": label_presentations,
        "source_replay_label_presentations": replay_presented,
        "executed_suffix_label_presentations": recovery_presented,
        "true_source_observations_not_hidden_auditor": True,
        "source_class_weights": class_weights.tolist(),
        "mean_real_supervised_loss": loss_sum / actual_updates,
        "mean_frozen_source_action_distribution_kl": kl_sum / actual_updates,
        "actual_fit_seconds": time.perf_counter() - started,
        "source_replay_unique_labels": source_meta["unique_source_real_supervised_tokens"],
        "genuine_executed_recovery_unique_labels": recovery_meta[
            "unique_source_real_supervised_tokens"
        ],
    }
